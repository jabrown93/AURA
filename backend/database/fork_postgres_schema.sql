CREATE TABLE AUTH (
    singleton BIGINT PRIMARY KEY DEFAULT 1 CHECK (singleton = 1),
    token_secret TEXT NOT NULL
);
CREATE TABLE Config (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE ConfigSchemaVersion (version BIGINT NOT NULL);
CREATE TABLE MediaItems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    rating_key TEXT NOT NULL,
    type TEXT NOT NULL CHECK (type IN ('movie','show')),
    title TEXT NOT NULL,
    year BIGINT NOT NULL,
    on_server BIGINT NOT NULL DEFAULT 0 CHECK (on_server IN (0,1)),
    added_at BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT NOT NULL DEFAULT 0,
    released_at BIGINT NOT NULL DEFAULT 0,
    latest_episode_added_at BIGINT NOT NULL DEFAULT 0,
    content_rating TEXT NOT NULL DEFAULT '',
    summary TEXT NOT NULL DEFAULT '',
    guids JSONB NOT NULL DEFAULT '[]',
    first_seen_at BIGINT NOT NULL DEFAULT 0,
    last_seen_at BIGINT NOT NULL DEFAULT 0,
    UNIQUE (tmdb_id, library_title, edition)
);
CREATE TABLE Movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_item_id BIGINT NOT NULL UNIQUE REFERENCES MediaItems(id) ON DELETE CASCADE ON UPDATE CASCADE,
    path TEXT NOT NULL,
    size BIGINT NOT NULL,
    duration BIGINT NOT NULL
);
CREATE TABLE Series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    media_item_id BIGINT NOT NULL UNIQUE REFERENCES MediaItems(id) ON DELETE CASCADE ON UPDATE CASCADE,
    season_count BIGINT,
    episode_count BIGINT,
    location TEXT
);
CREATE TABLE Seasons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL REFERENCES Series(id) ON DELETE CASCADE ON UPDATE CASCADE,
    rating_key TEXT NOT NULL,
    season_number BIGINT NOT NULL,
    episode_count BIGINT,
    UNIQUE (series_id, season_number)
);
CREATE TABLE Episodes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id BIGINT NOT NULL REFERENCES Seasons(id) ON DELETE CASCADE ON UPDATE CASCADE,
    rating_key TEXT NOT NULL,
    episode_number BIGINT NOT NULL,
    title TEXT,
    path TEXT NOT NULL,
    size BIGINT NOT NULL,
    duration BIGINT NOT NULL,
    UNIQUE (season_id, episode_number)
);
CREATE TABLE PosterSets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id TEXT NOT NULL UNIQUE,
    type TEXT NOT NULL CHECK (type IN ('show','movie','collection')),
    title TEXT NOT NULL,
    "user" TEXT NOT NULL,
    date_created TIMESTAMPTZ,
    date_updated TIMESTAMPTZ
);
CREATE TABLE ImageFiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poster_set_id BIGINT NOT NULL REFERENCES PosterSets(id) ON DELETE CASCADE ON UPDATE CASCADE,
    item_tmdb_id TEXT NOT NULL,
    image_id TEXT NOT NULL,
    image_type TEXT NOT NULL CHECK (image_type IN ('poster','backdrop','season_poster','titlecard')),
    image_last_updated TIMESTAMPTZ NOT NULL,
    image_season_number BIGINT,
    image_episode_number BIGINT,
    UNIQUE (poster_set_id, image_id, item_tmdb_id)
);
CREATE TABLE SavedItems (
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    poster_set_id BIGINT NOT NULL REFERENCES PosterSets(id) ON DELETE CASCADE ON UPDATE CASCADE,
    poster_selected BIGINT NOT NULL DEFAULT 0 CHECK (poster_selected IN (0,1)),
    backdrop_selected BIGINT NOT NULL DEFAULT 0 CHECK (backdrop_selected IN (0,1)),
    season_poster_selected BIGINT NOT NULL DEFAULT 0 CHECK (season_poster_selected IN (0,1)),
    special_season_poster_selected BIGINT NOT NULL DEFAULT 0 CHECK (special_season_poster_selected IN (0,1)),
    titlecard_selected BIGINT NOT NULL DEFAULT 0 CHECK (titlecard_selected IN (0,1)),
    autodownload BIGINT NOT NULL DEFAULT 0 CHECK (autodownload IN (0,1)),
    auto_add_new_collection_items BIGINT NOT NULL DEFAULT 0 CHECK (auto_add_new_collection_items IN (0,1)),
    no_auto_upgrade BIGINT NOT NULL DEFAULT 0 CHECK (no_auto_upgrade IN (0,1)),
    force_preload_missing BIGINT NOT NULL DEFAULT 0 CHECK (force_preload_missing IN (0,1)),
    last_downloaded TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (tmdb_id, library_title, edition, poster_set_id),
    FOREIGN KEY (tmdb_id, library_title, edition) REFERENCES MediaItems(tmdb_id, library_title, edition) ON DELETE CASCADE ON UPDATE CASCADE DEFERRABLE INITIALLY DEFERRED
);
CREATE TABLE IgnoredItems (
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    mode TEXT NOT NULL CHECK (mode IN ('always','until-set-available','until-new-set-available')),
    current_sets JSONB NOT NULL DEFAULT '[]',
    PRIMARY KEY (tmdb_id, library_title, edition)
);
CREATE TABLE DownloadQueueJobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    media_item_title TEXT NOT NULL,
    payload JSONB NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','processing','success','warning','error')),
    result_message TEXT NOT NULL DEFAULT '',
    result_errors JSONB NOT NULL DEFAULT '[]',
    result_warnings JSONB NOT NULL DEFAULT '[]',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    worker_id TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_downloadqueuejobs_status ON DownloadQueueJobs(status, created_at);
CREATE INDEX idx_downloadqueuejobs_item ON DownloadQueueJobs(tmdb_id, library_title, edition);
CREATE UNIQUE INDEX idx_downloadqueuejobs_running_item ON DownloadQueueJobs(tmdb_id, library_title, edition) WHERE status = 'processing';
CREATE TABLE DownloadHistory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    media_item_title TEXT NOT NULL,
    media_item_year BIGINT NOT NULL,
    set_id TEXT NOT NULL,
    set_title TEXT NOT NULL,
    set_creator TEXT NOT NULL DEFAULT '',
    selected_types JSONB NOT NULL DEFAULT '{}',
    warning_count BIGINT NOT NULL DEFAULT 0,
    images_succeeded BIGINT NOT NULL DEFAULT 0,
    images_failed BIGINT NOT NULL DEFAULT 0,
    status TEXT NOT NULL CHECK (status IN ('success','warning','error')),
    failed_images JSONB NOT NULL DEFAULT '[]',
    retry_count BIGINT NOT NULL DEFAULT 0,
    next_retry_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source TEXT NOT NULL DEFAULT ''
);
CREATE INDEX idx_downloadhistory_status_created ON DownloadHistory(status, created_at);
CREATE TABLE SiloItemIDs (
