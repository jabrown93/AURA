    imdb_id TEXT NOT NULL DEFAULT '',
    tvdb_id TEXT NOT NULL DEFAULT '',
    first_air_date TEXT NOT NULL DEFAULT '',
    season_count BIGINT NOT NULL DEFAULT 0,
    episode_count BIGINT NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE Collections (
    rating_key TEXT PRIMARY KEY,
    library_title TEXT NOT NULL,
    collection_index TEXT NOT NULL DEFAULT '',
    tmdb_id TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL,
    summary TEXT NOT NULL DEFAULT '',
    child_count BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE CollectionItems (
    collection_rating_key TEXT NOT NULL,
    rating_key TEXT NOT NULL,
    tmdb_id TEXT NOT NULL DEFAULT '',
    library_title TEXT NOT NULL DEFAULT '',
    title TEXT NOT NULL DEFAULT '',
    year BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (collection_rating_key, rating_key)
);
CREATE INDEX idx_collectionitems_tmdb_id ON CollectionItems(tmdb_id);
CREATE TABLE DownloadEvents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tmdb_id TEXT NOT NULL,
    library_title TEXT NOT NULL,
    edition TEXT NOT NULL DEFAULT '',
    media_item_title TEXT NOT NULL DEFAULT '',
    media_item_type TEXT NOT NULL DEFAULT '',
    set_id TEXT NOT NULL DEFAULT '',
    set_title TEXT NOT NULL DEFAULT '',
    set_type TEXT NOT NULL DEFAULT '',
    set_creator TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('download','update','reapply','saved')),
    images_succeeded BIGINT NOT NULL DEFAULT 0,
    images_failed BIGINT NOT NULL DEFAULT 0,
    image_types JSONB NOT NULL DEFAULT '{}',
    bytes BIGINT NOT NULL DEFAULT 0,
    estimated BIGINT NOT NULL DEFAULT 0 CHECK (estimated IN (0,1)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_downloadevents_created ON DownloadEvents(created_at);
CREATE INDEX idx_downloadevents_item_set ON DownloadEvents(tmdb_id, library_title, edition, set_id);
